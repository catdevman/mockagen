// TestIntegrationInspect pins the schema YAML each engine actually
// produces. The four strings differ on purpose: sql_type is the server's
// own spelling, and that spelling is the fact the file has to keep.
func TestIntegrationInspect(t *testing.T) {
	at := time.Date(2026, 10, 12, 14, 3, 11, 0, time.UTC)
	for _, tg := range dbtest.Targets() {
		t.Run(tg.Dialect, func(t *testing.T) {
			tg.Setup(t)
			for _, stmt := range fixtureSQL[tg.Dialect] {
				tg.Query(t, stmt)
			}
			q := openQuerier(t, tg)
			req := Request{
				Dialect:  tg.Dialect,
				Schema:   fixtureSchema[tg.Dialect],
				Table:    "users",
				Database: fixtureDB[tg.Dialect],
				At:       at,
			}
			got, err := Inspect(context.Background(), q, req)
			if err != nil {
				t.Fatal(err)
			}
			body, err := schema.Marshal(got, ".yaml")
			if err != nil {
				t.Fatal(err)
			}
			if string(body) != wantYAML[tg.Dialect] {
				t.Fatalf("yaml =\n%s\nwant:\n%s", body, wantYAML[tg.Dialect])
			}
		})
	}
}

func openQuerier(t *testing.T, tg dbtest.Target) Querier {
	t.Helper()
	if tg.Dialect == "sqlite" {
		return SQLiteCLI{DB: dbtest.SQLiteDBPath}
	}
	driver := map[string]string{
		"postgres": "pgx",
		"mysql":    "mysql",
		"mssql":    "sqlserver",
	}[tg.Dialect]
	db, err := sql.Open(driver, tg.DSN(t))
	if err != nil {
		t.Fatalf("open %s: %v", tg.Dialect, err)
	}
	t.Cleanup(func() { _ = db.Close() })
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		t.Fatalf("ping %s: %v", tg.Dialect, err)
	}
	return SQLQuerier{DB: db}
}

